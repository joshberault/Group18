/** Prefer pass-through live catalog; empty default (never seed). */
export function getInvoiceAttorneys(invoices: Invoice[] = []): string[] {
  return Array.from(
    new Set(
      invoices
        .map((i) => i.attorney?.trim())
        .filter((name): name is string => Boolean(name)),
    ),
  ).sort();
}
