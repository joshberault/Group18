type PeriodSeedRow = {
  id: string;
  invoiceNumber: string;
  client: keyof typeof CLIENT_PROFILES;
  legalMatter: string;
  attorney: string;
  billingMethod: Invoice["billingMethod"];
  invoiceDate: string;
  dueDate: string;
  totalAmount: number;
  amountPaid: number;
  status: Invoice["status"];
  matterDescription: string;
  payments?: { date: string; method: string; reference: string; amount: number }[];
  lastReminderSent?: string | null;
  reminderCount?: number;
  reminderStatus?: Invoice["reminderStatus"];
};

function buildPeriodSeedInvoice(row: PeriodSeedRow): Invoice {
  const remaining = Math.max(0, Math.round((row.totalAmount - row.amountPaid) * 100) / 100);
  const teId = `${row.id}-te`;
  return {
    id: row.id,
    invoiceNumber: row.invoiceNumber,
    client: row.client,
    legalMatter: row.legalMatter,
    attorney: row.attorney,
    billingMethod: row.billingMethod,
    invoiceDate: row.invoiceDate,
    dueDate: row.dueDate,
    totalAmount: row.totalAmount,
    amountPaid: row.amountPaid,
    remainingBalance: remaining,
    status: row.status,
    clientInfo: { ...CLIENT_PROFILES[row.client] },
    matterDescription: row.matterDescription,
    timeEntries: [
      {
        id: teId,
        date: row.invoiceDate,
        attorney: row.attorney,
        description: "Professional services for the billing period",
        hours: Math.max(1, Math.round((row.totalAmount / 550) * 10) / 10),
        rate: 550,
        amount: row.totalAmount,
      },
    ],
    reimbursableExpenses: [],
    writeDowns: [],
    retainerApplied: 0,
    paymentHistory: (row.payments ?? []).map((p, i) => ({
      id: `${row.id}-pay-${i + 1}`,
      ...p,
    })),
    lastReminderSent: row.lastReminderSent,
    reminderCount: row.reminderCount,
    reminderStatus: row.reminderStatus,
  };
}

